-- Merchant commerce records, product variants, domains and subscription lifecycle.
create table if not exists public.customers (
 id uuid primary key default gen_random_uuid(), store_id uuid not null references public.stores(id) on delete cascade,
 email text not null, full_name text, phone text, total_orders integer not null default 0,
 total_spent numeric(12,2) not null default 0, created_at timestamptz not null default now(),
 updated_at timestamptz not null default now(), unique(store_id,email)
);
create table if not exists public.orders (
 id uuid primary key default gen_random_uuid(), store_id uuid not null references public.stores(id) on delete cascade,
 customer_id uuid references public.customers(id) on delete set null, order_number bigint generated by default as identity,
 email text not null, customer_name text not null, phone text, shipping_address jsonb not null default '{}'::jsonb,
 currency text not null default 'NGN', subtotal numeric(12,2) not null default 0,
 shipping_total numeric(12,2) not null default 0, discount_total numeric(12,2) not null default 0,
 total numeric(12,2) not null default 0, payment_provider text, payment_reference text unique,
 payment_status text not null default 'pending' check(payment_status in ('pending','paid','failed','refunded','partially_refunded')),
 fulfillment_status text not null default 'unfulfilled' check(fulfillment_status in ('unfulfilled','processing','shipped','delivered','cancelled','returned')),
 notes text, paid_at timestamptz, created_at timestamptz not null default now(), updated_at timestamptz not null default now(),
 unique(store_id,order_number)
);
create table if not exists public.product_variants (
 id uuid primary key default gen_random_uuid(), product_id uuid not null references public.products(id) on delete cascade,
 store_id uuid not null references public.stores(id) on delete cascade, title text not null, sku text,
 price numeric(12,2) not null check(price>=0), inventory_quantity integer not null default 0 check(inventory_quantity>=0),
 options jsonb not null default '{}'::jsonb, is_active boolean not null default true,
 created_at timestamptz not null default now(), updated_at timestamptz not null default now()
);
create table if not exists public.order_items (
 id uuid primary key default gen_random_uuid(), order_id uuid not null references public.orders(id) on delete cascade,
 product_id uuid references public.products(id) on delete set null, variant_id uuid references public.product_variants(id) on delete set null,
 product_title text not null, variant_title text, sku text, quantity integer not null check(quantity>0),
 unit_price numeric(12,2) not null check(unit_price>=0), line_total numeric(12,2) not null check(line_total>=0),
 image_path text, created_at timestamptz not null default now()
);
create table if not exists public.subscription_plans (
 id uuid primary key default gen_random_uuid(), name text not null unique, slug text not null unique,
 description text, price_monthly numeric(12,2) not null default 0, currency text not null default 'NGN',
 product_limit integer, staff_limit integer, features jsonb not null default '[]'::jsonb,
 is_active boolean not null default true, provider_plan_code text unique, created_at timestamptz not null default now()
);
create table if not exists public.store_subscriptions (
 id uuid primary key default gen_random_uuid(), store_id uuid not null references public.stores(id) on delete cascade,
 plan_id uuid not null references public.subscription_plans(id), status text not null default 'trialing'
 check(status in ('trialing','active','past_due','cancelled','expired')), billing_provider text,
 provider_customer_code text, provider_subscription_code text, current_period_start timestamptz,
 current_period_end timestamptz, cancel_at_period_end boolean not null default false,
 created_at timestamptz not null default now(), updated_at timestamptz not null default now()
);
create unique index if not exists store_subscriptions_one_current_idx on public.store_subscriptions(store_id) where status in ('trialing','active','past_due');
create table if not exists public.store_domains (
 id uuid primary key default gen_random_uuid(), store_id uuid not null references public.stores(id) on delete cascade,
 domain text not null unique, verification_status text not null default 'pending'
 check(verification_status in ('pending','verified','failed')), is_primary boolean not null default false,
 created_at timestamptz not null default now()
);
create table if not exists public.payment_events (
 id uuid primary key default gen_random_uuid(), store_id uuid references public.stores(id) on delete set null,
 order_id uuid references public.orders(id) on delete set null, provider text not null,
 provider_event_id text unique, event_type text not null, payload jsonb not null default '{}'::jsonb,
 processed_at timestamptz, created_at timestamptz not null default now()
);
create index if not exists customers_store_email_idx on public.customers(store_id,email);
create index if not exists orders_store_created_idx on public.orders(store_id,created_at desc);
create index if not exists orders_store_payment_idx on public.orders(store_id,payment_status);
create index if not exists order_items_order_idx on public.order_items(order_id);
create index if not exists product_variants_product_idx on public.product_variants(product_id);
create index if not exists subscriptions_store_status_idx on public.store_subscriptions(store_id,status);
create index if not exists domains_store_idx on public.store_domains(store_id);
alter table public.customers enable row level security;
alter table public.orders enable row level security;
alter table public.order_items enable row level security;
alter table public.product_variants enable row level security;
alter table public.subscription_plans enable row level security;
alter table public.store_subscriptions enable row level security;
alter table public.store_domains enable row level security;
alter table public.payment_events enable row level security;
drop policy if exists "customers_store_members_all" on public.customers;
create policy "customers_store_members_all" on public.customers for all to authenticated using(private.can_access_store(store_id)) with check(private.can_access_store(store_id));
drop policy if exists "orders_store_members_all" on public.orders;
create policy "orders_store_members_all" on public.orders for all to authenticated using(private.can_access_store(store_id)) with check(private.can_access_store(store_id));
drop policy if exists "order_items_store_members_all" on public.order_items;
create policy "order_items_store_members_all" on public.order_items for all to authenticated using(exists(select 1 from public.orders o where o.id=order_id and private.can_access_store(o.store_id))) with check(exists(select 1 from public.orders o where o.id=order_id and private.can_access_store(o.store_id)));
drop policy if exists "variants_store_members_all" on public.product_variants;
create policy "variants_store_members_all" on public.product_variants for all to authenticated using(private.can_access_store(store_id)) with check(private.can_access_store(store_id));
drop policy if exists "plans_read_active" on public.subscription_plans;
create policy "plans_read_active" on public.subscription_plans for select to authenticated using(is_active);
drop policy if exists "subscriptions_store_members_select" on public.store_subscriptions;
create policy "subscriptions_store_members_select" on public.store_subscriptions for select to authenticated using(private.can_access_store(store_id));
drop policy if exists "domains_store_members_all" on public.store_domains;
create policy "domains_store_members_all" on public.store_domains for all to authenticated using(private.can_access_store(store_id)) with check(private.can_access_store(store_id));
drop policy if exists "payment_events_store_members_select" on public.payment_events;
create policy "payment_events_store_members_select" on public.payment_events for select to authenticated using(store_id is not null and private.can_access_store(store_id));
grant select,insert,update,delete on public.customers,public.orders,public.order_items,public.product_variants,public.store_domains to authenticated;
grant select on public.subscription_plans,public.store_subscriptions,public.payment_events to authenticated;
grant usage,select on all sequences in schema public to authenticated;
